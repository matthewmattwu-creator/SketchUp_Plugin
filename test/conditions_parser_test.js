'use strict';
const assert=require('node:assert/strict');
const P=require('../src/buildable_envelope/conditions_parser');
let checks=0;function check(fn){fn();checks++;}
const sample='限高36米；道路侧退线8米；邻地侧退线3米；组2退线5米；层高3.6米';
const result=P.parse(sample);
check(()=>assert.equal(result.actions.length,5));
check(()=>assert.equal(result.warnings.length,0));
check(()=>assert.deepEqual(result.actions.map(a=>a.target),['all','road','neighbor','group','all']));
check(()=>assert.equal(P.parse('限高３６ｍ；退线500厘米').actions[1].value,5));
check(()=>assert.equal(P.parse('第2组退线5000mm').actions[0].index,1));
check(()=>assert.equal(P.number('三十六'),36));
check(()=>assert.equal(P.number('一百零五'),105));
check(()=>assert.equal(P.number('三点六'),3.6));
check(()=>assert.equal(P.number('二零二'),202));
check(()=>assert.equal(P.parse('限高36米；限高45米').actions.filter(a=>a.valid).length,0));
check(()=>assert.equal(P.parse('限高36米；限高36米').actions.length,1));
check(()=>assert.ok(P.parse('限高36').warnings.length));
check(()=>assert.equal(P.parse('限高24至36米').actions.filter(a=>a.valid).length,0));
check(()=>assert.equal(P.parse('限高36米-45米').actions.filter(a=>a.valid).length,0));
check(()=>assert.equal(P.parse('限高-36米').actions[0].valid,false));
check(()=>assert.equal(P.parse('北侧退线5米').actions[0].target,'unmapped'));
check(()=>assert.equal(P.parse('道路红线宽度30米').actions.length,0));
check(()=>assert.equal(P.parse('限高不小于36米').actions[0].valid,false));
check(()=>assert.throws(()=>P.parse('x'.repeat(30001)),/超过/));
check(()=>assert.equal(P.parse('道路侧后退红线不得小于8米').actions[0].value,8));
const parcel={points:[[0,0],[10,0],[10,10],[0,10]],setbacks:[5,5,5,5],edgeLabels:['道路侧','邻地侧','未标注','未标注'],height:20,floor_height:3,groups:[{edges:[0]},{edges:[1,2,3]}],selectedGroups:new Set([1]),viewMode:'groups'};
const before=JSON.stringify(parcel);
const plan=P.plan(parcel,P.parse('限高36米；道路侧退线8米；邻地侧退线3米').actions);
check(()=>assert.deepEqual(plan.setbacks,[8,3,5,5]));
check(()=>assert.equal(plan.height,36));
check(()=>assert.equal(JSON.stringify(parcel),before));
check(()=>assert.deepEqual(P.plan(parcel,P.parse('退线2米；道路侧退线8米').actions).setbacks,[8,2,2,2]));
check(()=>assert.throws(()=>P.plan(parcel,P.parse('道路侧退线8米；原边1退线9米').actions),/不同退距/));
check(()=>assert.throws(()=>P.plan(parcel,P.parse('组9退线8米').actions),/不存在/));
check(()=>assert.throws(()=>P.plan({...parcel,edgeLabels:['未标注','未标注','未标注','未标注']},P.parse('道路侧退线8米').actions),/没有匹配/));
check(()=>assert.deepEqual(P.plan(parcel,[{...P.parse('退线8米').actions[0],target:'selected'}]).setbacks,[5,8,8,8]));
check(()=>assert.deepEqual(P.plan(parcel,[{...P.parse('北侧退线8米').actions[0],target:'group',index:1}]).setbacks,[5,8,8,8]));
check(()=>assert.throws(()=>P.plan(parcel,P.parse('限高36米；限高45米').actions),/冲突/));
check(()=>assert.equal(JSON.stringify(parcel),before));
console.log(checks+' planning text and atomic application checks passed.');
